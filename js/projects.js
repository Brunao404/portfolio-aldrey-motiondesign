function getPreviewUrl(projeto) {
  if (projeto.fonte === "local") {
    return projeto.tipo === "imagem"
      ? `/media/images/${projeto.id}.jpg`
      : `/media/gifs/${projeto.id}.gif`;
  }
  if (projeto.idPrevia && projeto.idPrevia !== "PLACEHOLDER_ID") {
    // Thumbnail gerado automaticamente pelo Drive
    return `https://drive.google.com/thumbnail?id=${projeto.idPrevia}&sz=w800`;
  }
  return "";
}

function getPreviewFallbackUrl(projeto) {
  if (projeto.idPrevia && projeto.idPrevia !== "PLACEHOLDER_ID") {
    return `https://lh3.googleusercontent.com/d/${projeto.idPrevia}`;
  }
  return "";
}

function getVideoEmbedUrl(projeto) {
  if (projeto.fonte === "drive") {
    return `https://drive.google.com/file/d/${projeto.idArquivo}/preview`;
  }
  if (projeto.fonte === "youtube") {
    return `https://www.youtube.com/embed/${projeto.idArquivo}?autoplay=1&rel=0`;
  }
  if (projeto.fonte === "vimeo") {
    return `https://player.vimeo.com/video/${projeto.idArquivo}?autoplay=1`;
  }
  if (projeto.fonte === "local") {
    return `/media/videos/${projeto.id}.mp4`;
  }
  return "";
}

function isPlaceholder(projeto) {
  return !projeto.idArquivo || projeto.idArquivo === "PLACEHOLDER_ID";
}
